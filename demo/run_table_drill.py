section("场景 7：各类非法输入一律定位并拒绝（不悄悄补数据）")

expect_error("缺失 </td>（</tr> 撞见未闭合的 td）", HtmlStructureError,
             lambda: extract_table(
                 b'<table id="x"><tr><td>a</tr></table>', "x", 0),
             tokens=("闭合", "第 1 行"))
expect_error("文档结束仍有未闭合标签", HtmlStructureError,
             lambda: extract_table(
                 b'<table id="x"><tr><td>a</td></tr>', "x", 0),
             tokens=("未闭合",))
expect_error("<td> 直接放在 <table> 下", HtmlStructureError,
             lambda: extract_table(
                 b'<table id="x"><td>a</td></table>', "x", 0),
             tokens=("<table>",))
expect_error("<tr> 里嵌套 <tr>", HtmlStructureError,
             lambda: extract_table(
                 b'<table id="x"><tr><tr><td>a</td></tr></tr></table>',
                 "x", 0),
             tokens=("<tr>",))
expect_error("单元格内非法嵌套 <td>（未隔着 table）", HtmlStructureError,
             lambda: extract_table(
                 b'<table id="x"><tr><td><span><td>b</td></span></td></tr></table>',
                 "x", 0),
             tokens=("嵌套",))
expect_error("<table> 下直接出现文本", HtmlStructureError,
             lambda: extract_table(
                 b'<table id="x">hello<tr><td>a</td></tr></table>', "x", 0),
             tokens=("文本",))
expect_error("id 在文档中不存在", TableNotFoundError,
             lambda: extract_table(
                 b'<table id="a"><tr><td>1</td></tr></table>', "ghost", 0),
             tokens=("ghost", "'a'"))
expect_error("两个表格同名 id", DuplicateTableIdError,
             lambda: extract_table(
                 b'<table id="x"><tr><td>1</td></tr></table>'
                 b'<table id="x"><tr><td>2</td></tr></table>', "x", 0),
             tokens=("2 个",))
expect_error("rowspan 为负数", SpanAttributeError,
             lambda: extract_table(
                 b'<table id="x"><tr><td rowspan="-1">a</td></tr></table>',
                 "x", 0),
             tokens=("rowspan", "-1"))
expect_error("colspan 为小数", SpanAttributeError,
             lambda: extract_table(
                 b'<table id="x"><tr><td colspan="1.5">a</td></tr></table>',
                 "x", 0),
             tokens=("colspan", "1.5"))
expect_error("colspan 为 0", SpanAttributeError,
             lambda: extract_table(
                 b'<table id="x"><tr><td colspan="0">a</td></tr></table>',
                 "x", 0),
             tokens=("colspan",))
expect_error("rowspan 为全角数字", SpanAttributeError,
             lambda: extract_table(
                 '<table id="x"><tr><td rowspan="２">a</td></tr></table>'
                 .encode("utf-8"), "x", 0),
             tokens=("rowspan",))
expect_error("rowspan 属性重复", SpanAttributeError,
             lambda: extract_table(
                 b'<table id="x"><tr><td rowspan="1" rowspan="2">a</td></tr></table>',
                 "x", 0),
             tokens=("重复",))
expect_error("rowspan 没有属性值", SpanAttributeError,
             lambda: extract_table(
                 b'<table id="x"><tr><td rowspan>a</td></tr></table>',
                 "x", 0),
             tokens=("rowspan",))
expect_error("正数 rowspan 越过本 tbody 末行", RowspanOutOfGroupError,
             lambda: extract_table(
                 b'<table id="x"><tbody><tr><td rowspan="3">a</td></tr>'
                 b'<tr><td>b</td></tr></tbody></table>', "x", 0),
             tokens=("rowspan=3", "共 2 行"))
expect_error("rowspan 同时覆盖标题行与数据行", HeaderBoundaryError,
             lambda: extract_table(
                 b'<table id="x"><tr><th rowspan="2">h</th></tr>'
                 b'<tr><td>d</td></tr></table>', "x", 1),
             tokens=("标题行", "数据行"))
expect_error("header_rows 超过实际行数", HeaderRowsError,
             lambda: extract_table(
                 b'<table id="x"><tr><td>a</td></tr></table>', "x", 2),
             tokens=("header_rows=2", "1 行"))
expect_error("非法 UTF-8 字节", InvalidUtf8Error,
             lambda: extract_table(
                 b'<table id="x"><tr><td>\xff\xfe</td></tr></table>',
                 "x", 0),
             tokens=("UTF-8",))

# 参数本身非法（调用约定）
for bad, name in [(-1, "负数"), (2.5, "小数"), (True, "布尔")]:
    expect_error(f"header_rows={bad!r}（{name}）", ValueError,
                 lambda b=bad: extract_table(b"<table id='x'/>", "x", b))

# 合法但容易误判的输入：应当接受
ok = extract_table(
    b'<TABLE ID="up"><TR><TD ROWSPAN=" 2 ">a</TD></TR>'
    b'<TR><TD>b</TD></TR></TABLE>', "up", 0)
expect_eq("标签/属性名大写 + 跨度含首尾空白：合法",
          (ok.grid, ok.source_cells[0].span_rows),
          ([[0, None], [0, 1]], 2))
expect_error("id 属性值区分大小写（'UP' 找不到）", TableNotFoundError,
             lambda: extract_table(
                 b'<table id="UP"><tr><td>a</td></tr></table>', "up", 0),
             tokens=("up",))

