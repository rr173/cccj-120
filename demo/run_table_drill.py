"""Repeatable, no-network acceptance drill for tableextract.

Run from the repository root:

    python3 -I demo/run_table_drill.py

The script is fully self-contained (stdlib only): it reads the hand-made
HTML fixtures under demo/table_fixtures/, runs the extractor, and
compares every coordinate, header path and value against expectations
that are *hand-listed below as literals* -- never regenerated by calling
the layout code a second time.  Key cells are printed with their source
tag positions (line + column offset, with the original line quoted), the
per-column header paths and the actual expanded data, so a reviewer can
see the trace from a data value back to its original tag, not just a
pass count.

Scenarios (mirrors the task contract):
  1. regional_stats.html  地区列跨行 + 两层“年份/指标”跨列表头；tbody 内
     的 th 保留为数据；表头里的 <br>；逐格核对展开坐标与来源行号；
  2. rowspan_zero.html    rowspan=0 延伸到本 tbody 末行、绝不流进下一个
     tbody；header_rows=0（无表头）；
  3. nested_tables.html   单元格里的内层表格不进入外层单元格、不增加外层
     行列；内层表按自己的 id 单独提取又是一张正常的表；
  4. text_semantics.html  字符实体解码、<br> 视为空格、连续空白折叠、
     &nbsp; 保留、注释/script/style 不计入数据；
  5. gaps.html            真实空单元格（文本 ""）与补齐出来的 null 缺口
     明确区分；
  6. conflict.html        横跨单元格撞上前行跨行占位：定位并拒绝，绝不
     生成错列结果（CLI 也退出非零、stdout 为空）；
  7. 拒绝全集             缺失闭合/非法嵌套/结构错位、重复 id、id 不存在、
     负/小数/全角/重复跨度、rowspan 越行组、跨标题数据边界、header_rows
     超行数、非法 UTF-8、输入与网格上限；
  8. 稳定性与 CLI         相同输入重复提取结果逐字节一致；命令行入口对
     本地文件实际运行，成功出 JSON、失败非零退出且 stdout 不留半份结果。
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from tableextract import (  # noqa: E402
    DuplicateTableIdError,
    HeaderBoundaryError,
    HeaderRowsError,
    HtmlStructureError,
    InputTooLargeError,
    InvalidUtf8Error,
    LayoutConflictError,
    ResultLimitError,
    RowspanOutOfGroupError,
    SpanAttributeError,
    TableExtractError,
    TableNotFoundError,
    extract_table,
)

FIXTURES = Path(__file__).resolve().parent / "table_fixtures"

failures: list[str] = []
checks = 0


def expect(label: str, condition: bool, detail: str = "") -> None:
    global checks
    checks += 1
    status = "PASS" if condition else "FAIL"
    line = f"  [{status}] {label}"
    if not condition and detail:
        line += f"  -- 实际: {detail}"
    print(line)
    if not condition:
        failures.append(label)


def expect_eq(label: str, actual, expected) -> None:
    expect(label, actual == expected,
           f"{actual!r}（期望 {expected!r}）")


def expect_error(label: str, exc_type, fn, tokens=()):
    """fn() must raise exc_type whose message contains every token."""
    global checks
    checks += 1
    try:
        fn()
    except exc_type as exc:
        text = str(exc)
        missing = [t for t in tokens if t not in text]
        if missing:
            print(f"  [FAIL] {label}  -- 错误信息缺少 {missing!r}: {text}")
            failures.append(label)
        else:
            print(f"  [PASS] {label}\n         拒绝原因: {text}")
        return exc
    except Exception as exc:  # noqa: BLE001 - 类型不对也是失败
        print(f"  [FAIL] {label}  -- 抛出 {type(exc).__name__}: {exc}")
        failures.append(label)
        return None
    print(f"  [FAIL] {label}  -- 没有报错，悄悄产出了结果")
    failures.append(label)
    return None


def section(title: str) -> None:
    print("\n" + "=" * 76)
    print(title)
    print("=" * 76)


def load(name: str) -> bytes:
    return (FIXTURES / name).read_bytes()


def show_source(lines: list[str], cell, note: str = "") -> None:
    """Print the trace from one cell back to its tag in the source file."""
    tag = f"第 {cell.line} 行第 {cell.col_offset} 列"
    print(f"      源单元格 #{cell.index} <{cell.kind}> "
          f"展开位置 (行 {cell.row}, 列 {cell.col}) "
          f"跨度 {cell.span_rows}行×{cell.span_cols}列 {note}")
    print(f"      起始标签: {tag}  →  {lines[cell.line - 1].strip()}")


def run_cli(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "tableextract", *args],
        cwd=REPO, capture_output=True, text=True)


