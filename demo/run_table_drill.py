section("场景 8：输入 4 MiB、1 万行、256 列、200 万格位置上限")

expect_error("输入超过 4 MiB", InputTooLargeError,
             lambda: extract_table(b"x" * (4 * 1024 * 1024 + 1), "x", 0),
             tokens=("4 MiB",))
expect_error("10001 行超过行数上限", ResultLimitError,
             lambda: extract_table(
                 ("<table id='x'>" + "<tr><td>a</td></tr>" * 10001
                  + "</table>").encode(), "x", 0),
             tokens=("10001", "10000"))
expect_error("257 列超过列数上限", ResultLimitError,
             lambda: extract_table(
                 ("<table id='x'><tr>" + "<td>a</td>" * 257
                  + "</tr></table>").encode(), "x", 0),
             tokens=("257", "256"))
expect_error("10000×201 超过网格位置上限", ResultLimitError,
             lambda: extract_table(
                 ("<table id='x'>" + "<tr><td colspan='201'>a</td></tr>" * 10000
                  + "</table>").encode(), "x", 0),
             tokens=("2010000", "2000000"))
edge = extract_table(
    ("<table id='x'>" + "<tr><td>a</td></tr>" * 10000 + "</table>").encode(),
    "x", 0)
expect_eq("恰好 10000 行 × 1 列：在上限内，正常提取",
          (edge.n_rows, edge.n_cols), (10000, 1))

